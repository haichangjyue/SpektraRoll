#pragma once

// Numeric tables for the M1 colour chain, sampled at 380..780 nm, 5 nm steps
// (81 samples), matching spektrafilm's SPECTRAL_SHAPE.
//
// Sources:
//   * CIE 1931 2-degree standard observer, D55/D50 illuminants: colour-science
//     (BSD-3-Clause), derived from CIE 15:2004 tables.
//   * sRGB Mallett 2019 spectral upsampling basis: Mallett & Yuksel (2019),
//     via colour-science.
//   * TH-KG3 enlarger illuminant: Planckian 3400 K through a Schott KG3 heat
//     filter, as defined by spektrafilm.
//
// The arrays live in src/core/src/spectral_tables.cpp, generated by
// tools/parity/reference_model.py --dump-tables. Do not edit by hand.

namespace sr::data {

constexpr int kWavelengthCount = 81;

// Interleaved XYZ colour matching functions, 81 * 3.
extern const float kCmfs[];
// Normalised illuminants (mean == 1 over the 81 samples).
extern const float kIlluminantD55[];
extern const float kIlluminantD50[];
extern const float kIlluminantThKg3[];
// D065: T (tungsten / CIE A, the Vision3 200T/500T reference) and K75P
// (Kinoton 75P, the projector light a 2383 print is viewed under).
extern const float kIlluminantT[];
extern const float kIlluminantK75P[];
// Mallett 2019 sRGB basis, interleaved per wavelength: 81 * 3.
extern const float kMallettBasis[];

// Row-major 3x3: XYZ under the D50 viewing illuminant -> linear sRGB,
// CAT02 chromatic adaptation (colour-science's default for XYZ_to_RGB).
extern const float kXyzD50ToSrgb[9];

}  // namespace sr::data
